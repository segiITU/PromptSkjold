#!/usr/bin/env node
/**
 * Generates the two consumers of src/shared/design/tokens.json:
 *   - src/shared/styles/tokens.vars.css            (document :root, popup/options)
 *   - src/ui/shared/design-tokens.generated.ts      (Shadow DOM :host block)
 * so the light-DOM and Shadow-DOM token sets cannot drift.
 *
 * `render()` is exported for tests/ui/design-tokens.test.ts.
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const SRC = path.join(ROOT, 'src/shared/design/tokens.json');
const OUT_CSS = path.join(ROOT, 'src/shared/styles/tokens.vars.css');
const OUT_TS = path.join(ROOT, 'src/ui/shared/design-tokens.generated.ts');

function declarations(tokens, indent) {
  return Object.entries(tokens)
    .map(([k, v]) => `${indent}--${k}: ${v};`)
    .join('\n');
}

function render() {
  const { tokens } = JSON.parse(fs.readFileSync(SRC, 'utf8'));
  const header = '/* GENERATED by scripts/build-tokens.js from src/shared/design/tokens.json. Do not edit. */\n';
  const css = `${header}:root,\n:host {\n${declarations(tokens, '  ')}\n}\n`;
  const ts =
    `// GENERATED by scripts/build-tokens.js from src/shared/design/tokens.json. Do not edit.\n` +
    `export const SHADOW_DESIGN_TOKENS = \`\n  :host {\n${declarations(tokens, '    ')}\n  }\n\`;\n` +
    `/** Font stacks for inline styles in the host page (no CSS variables there). */\n` +
    `export const FONT_UI = ${JSON.stringify(tokens['f-ui'])};\n` +
    `export const FONT_MONO = ${JSON.stringify(tokens['f-mono'])};\n`;
  return { css, ts };
}

module.exports = { render, OUT_CSS, OUT_TS };

if (require.main === module) {
  const { css, ts } = render();
  fs.writeFileSync(OUT_CSS, css);
  fs.writeFileSync(OUT_TS, ts);
  console.log('tokens: wrote', path.relative(ROOT, OUT_CSS), 'and', path.relative(ROOT, OUT_TS));
}
