#!/usr/bin/env node
/**
 * Generates src/ui/shared/page-assets.generated.ts: the few fonts and the logo
 * that the in-page UI (review overlay, toast, chip ...) needs, embedded as
 * base64.
 *
 * Why embedded and not web_accessible_resources: exposing extension files to
 * the chat sites would let those sites detect that the extension is installed.
 * The fonts are registered through the FontFace API from bytes, so the host
 * page's Content-Security-Policy (font-src) does not apply either.
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const FONT_DIR = path.join(ROOT, 'src/assets/fonts');
const OUT = path.join(ROOT, 'src/ui/shared/page-assets.generated.ts');

const FONTS = [
  { family: 'PromptSkjold Sans', weight: '400', file: 'ibm-plex-sans-latin-400.woff2' },
  { family: 'PromptSkjold Sans', weight: '600', file: 'ibm-plex-sans-latin-600.woff2' },
  { family: 'PromptSkjold Serif', weight: '400', file: 'ibm-plex-serif-latin-400.woff2' },
];

function b64(file) {
  return fs.readFileSync(file).toString('base64');
}

function render() {
  const fonts = FONTS.map((f) => ({ family: f.family, weight: f.weight, data: b64(path.join(FONT_DIR, f.file)) }));
  const logo = b64(path.join(ROOT, 'src/assets/icons/icon128.png'));
  return (
    '// GENERATED by scripts/build-page-assets.js. Do not edit.\n' +
    '// Embedded fonts: IBM Plex Sans 400/600 and IBM Plex Serif 400 (Copyright IBM Corp., SIL OFL 1.1,\n' +
    '// licence texts in src/assets/fonts/LICENSE-IBM-Plex-*-OFL.txt; see THIRD_PARTY_NOTICES.md, Fonts).\n' +
    `export const PAGE_FONTS: ReadonlyArray<{ family: string; weight: string; data: string }> = ${JSON.stringify(fonts, null, 2)};\n` +
    `export const LOGO_DATA_URI = 'data:image/png;base64,${logo}';\n`
  );
}

module.exports = { render, OUT };

if (require.main === module) {
  fs.writeFileSync(OUT, render());
  console.log('page assets: wrote', path.relative(ROOT, OUT));
}
